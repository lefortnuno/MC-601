#!/usr/bin/env node
// Regenerates music.data.tsx and film.data.tsx from the Baboke Films YouTube
// channel, so new uploads show up on the site without manual data entry.
// Requires yt-dlp on PATH. Run via `npm run sync:youtube`.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const CHANNEL_URL = "https://www.youtube.com/@BABOKEFILMS/videos";
const AUTHOR = "Directed by Tony Braven";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

// Videos matching one of these are music releases (artist name, lyric video,
// clip, freestyle, "prod by ..."). Everything else defaults to the Film
// bucket (documentaries, cinematic shorts, event coverage, corporate reels).
const MUSIC_KEYWORDS = [
  /601\s*bro/i,
  /soudar[aà]/i,
  /vain.?af/i,
  /\bfmm\b/i,
  /soa avao/i,
  /lyric/i,
  /clip officiel/i,
  /freestyle/i,
  /prod\.?\s*by/i,
];

function isMusic(title) {
  return MUSIC_KEYWORDS.some((re) => re.test(title));
}

function formatDuration(totalSeconds) {
  const s = Math.max(0, Math.round(totalSeconds));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  const mm = h > 0 ? String(m).padStart(2, "0") : String(m);
  const ss = String(sec).padStart(2, "0");
  return h > 0 ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

function cleanTitle(title) {
  return title.replace(/\s+/g, " ").trim();
}

function fetchChannelVideos() {
  let json;
  try {
    json = execFileSync("yt-dlp", ["--flat-playlist", "-J", CHANNEL_URL], {
      maxBuffer: 1024 * 1024 * 50,
      encoding: "utf-8",
    });
  } catch (err) {
    throw new Error(
      `yt-dlp failed to list ${CHANNEL_URL}. Is yt-dlp installed and on PATH?\n${err.message}`
    );
  }

  const data = JSON.parse(json);
  const entries = (data.entries || []).filter((e) => e && e.id && e.title);
  if (entries.length === 0) {
    throw new Error(
      "yt-dlp returned zero videos — refusing to overwrite existing data files."
    );
  }
  return entries;
}

function toVideoItem(entry) {
  return {
    thumbnail: `https://i.ytimg.com/vi/${entry.id}/hqdefault.jpg`,
    duration: formatDuration(entry.duration || 0),
    title: cleanTitle(entry.title),
    author_name: AUTHOR,
    link: `https://www.youtube.com/watch?v=${entry.id}`,
  };
}

function renderDataFile(items) {
  const body = items
    .map(
      (v) => `  {
    thumbnail: "${v.thumbnail}",
    duration: "${v.duration}",
    title: ${JSON.stringify(v.title)},
    author_name: "${v.author_name}",
    link: "${v.link}",
  },`
    )
    .join("\n");

  return `export interface VideoItem {
  thumbnail: string;
  duration: string;
  title: string;
  author_name: string;
  link: string;
}

// Auto-generated by scripts/fetch-youtube-videos.mjs — do not edit by hand.
// Source: ${CHANNEL_URL}
export const videos: VideoItem[] = [
${body}
];
`;
}

function main() {
  const entries = fetchChannelVideos();

  const music = [];
  const film = [];
  for (const entry of entries) {
    (isMusic(entry.title) ? music : film).push(toVideoItem(entry));
  }

  writeFileSync(path.join(ROOT, "music.data.tsx"), renderDataFile(music));
  writeFileSync(path.join(ROOT, "film.data.tsx"), renderDataFile(film));

  console.log(
    `Synced ${entries.length} videos from ${CHANNEL_URL}: ${music.length} music, ${film.length} film.`
  );
}

main();
